<?php

namespace App\Console\Commands;

use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\File;

#[Signature('wallet:schema-sql {--path=database/sql/wallet-schema.sql : File to write, relative to the project root}')]
#[Description('Write the whole database structure (and the migrations log) to a SQL file that can be imported into an empty database')]
class ExportSchemaSql extends Command
{
    /**
     * Read-only: describes tables with SHOW CREATE TABLE and copies the migrations log.
     * No other table data is exported.
     */
    public function handle(): int
    {
        $path = base_path((string) $this->option('path'));
        $tables = collect(DB::select('SHOW FULL TABLES WHERE Table_type = "BASE TABLE"'))
            ->map(fn (object $row): string => (string) array_values((array) $row)[0])
            ->sort()
            ->values();

        $sql = [];
        $sql[] = '-- Wallet database structure, generated by `php artisan wallet:schema-sql`.';
        $sql[] = '-- Import into an EMPTY database created with: CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci.';
        $sql[] = '-- Contains table structure and the migrations log only, never user or financial data.';
        $sql[] = '-- Generated: '.now()->toDateTimeString().' UTC';
        $sql[] = '';
        $sql[] = 'SET NAMES utf8mb4;';
        $sql[] = 'SET FOREIGN_KEY_CHECKS = 0;';
        $sql[] = '';

        foreach ($tables as $table) {
            $create = (array) DB::selectOne('SHOW CREATE TABLE `'.str_replace('`', '``', $table).'`');
            $statement = (string) ($create['Create Table'] ?? array_values($create)[1]);
            $statement = preg_replace('/^CREATE TABLE /', 'CREATE TABLE IF NOT EXISTS ', $statement);
            $statement = preg_replace('/ AUTO_INCREMENT=\d+/', '', (string) $statement);

            $sql[] = '-- Table: '.$table;
            $sql[] = $statement.';';
            $sql[] = '';
        }

        if ($tables->contains('migrations')) {
            $rows = DB::table('migrations')->orderBy('id')->get(['migration', 'batch']);

            if ($rows->isNotEmpty()) {
                $values = $rows
                    ->map(fn (object $row): string => '('.DB::getPdo()->quote($row->migration).', '.(int) $row->batch.')')
                    ->implode(",\n  ");

                $sql[] = '-- Migrations log, so `php artisan migrate` knows these are already applied.';
                $sql[] = "INSERT INTO `migrations` (`migration`, `batch`) VALUES\n  ".$values.';';
                $sql[] = '';
            }
        }

        $sql[] = 'SET FOREIGN_KEY_CHECKS = 1;';

        File::ensureDirectoryExists(dirname($path));
        File::put($path, implode("\n", $sql)."\n");

        $this->components->info($tables->count().' tables written to '.str_replace(base_path().DIRECTORY_SEPARATOR, '', $path));

        return self::SUCCESS;
    }
}
